    // Lookup tables keyed by JapaneseTextNormalizer.matchKey, so spelling variants
    // (ﾆﾝｼﾞﾝ / ニンジン / にんじん) collapse onto one entry
    private val NORMALIZED_KEYWORDS: Map<String, FoodCategory> =
        KEYWORD_MAP.entries.associate { (keyword, category) -> JapaneseTextNormalizer.matchKey(keyword) to category }

    private val NORMALIZED_NON_FOOD: List<String> =
        NON_FOOD_KEYWORDS.map { JapaneseTextNormalizer.matchKey(it) }

    /**
     * Checks if the given line or item name matches any known food item.
     * Returns the matching FoodCategory or null if not food.
     */
    fun matchCategory(itemName: String): FoodCategory? = match(itemName)?.value

    /**
     * The match key of the dictionary keyword found in [itemName] ("ｷｬﾍﾞﾂ 1玉" → "きゃべつ"),
     * or null if it is not a food. Used to recognize repurchases of the same food.
     */
    fun matchKeyword(itemName: String): String? = match(itemName)?.key

    /** Longest dictionary keyword contained in the name, unless a non-food keyword appears. */
    private fun match(itemName: String): Map.Entry<String, FoodCategory>? {
        val key = JapaneseTextNormalizer.matchKey(itemName)
        if (key.isEmpty()) return null
        if (NORMALIZED_NON_FOOD.any { key.contains(it) }) return null
        return NORMALIZED_KEYWORDS.entries
            .filter { key.contains(it.key) }
            .maxByOrNull { it.key.length }
    }

    /** Every keyword as written, food and non-food: words OCR misreads can be corrected towards. */
    internal val allKeywords: Set<String> get() = KEYWORD_MAP.keys + NON_FOOD_KEYWORDS

    /** Whether [keyword] (any spelling) is a dictionary food keyword. */
    internal fun hasKeyword(keyword: String): Boolean =
        JapaneseTextNormalizer.matchKey(keyword) in NORMALIZED_KEYWORDS

    /** Category for manual entry: falls back to OTHER when the name is not in the dictionary. */
    fun guessCategory(itemName: String): FoodCategory = matchCategory(itemName) ?: FoodCategory.OTHER

    fun isFoodItem(itemName: String): Boolean = matchCategory(itemName) != null

    /** Keywords that fold to the same match key but disagree on category (should be empty). */
    internal fun conflictingKeywords(): List<String> =
        KEYWORD_MAP.entries
            .groupBy({ JapaneseTextNormalizer.matchKey(it.key) }, { it.value })
            .filterValues { it.distinct().size > 1 }
            .keys.toList()
}
